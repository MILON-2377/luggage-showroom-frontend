"use client";

import { useState } from "react";
import Link from "next/link";
import { useRouter } from "next/navigation";

import { Button } from "@/src/components/ui/button";
import { Card, CardContent } from "@/src/components/ui/card";

import { AdminLoginForm } from "./AdminLoginForm";
import { AdminMfaMethodSelector } from "./AdminMfaMethodsSelector";
import { PasskeyLoginForm } from "./PasskeyLoginForm";
import { RecoveryCodeLoginForm } from "./RecoveryCodeLoginForm";
import { TotpLoginForm } from "./TotpLoginForm";

import { useAdminLoginFlow } from "../hooks/useAdminLoginFlow";

import type {
  AdminLoginRequest,
  AdminMfaMethod,
  MfaVerificationResponse,
} from "../types/admin-login.types";

const STEP_META: Record<
  "credentials" | "method" | AdminMfaMethod,
  {
    badge: string;
    code: string;
    title: string;
    description: string;
  }
> = {
  credentials: {
    badge: "Privileged Access",
    code: "AUTH // 01",
    title: "Administrator Login",
    description:
      "Authenticate with your administrative credentials to enter the BAGGUAGE operations console.",
  },
  method: {
    badge: "Secondary Verification",
    code: "MFA // SELECT",
    title: "Select Factor",
    description:
      "Choose a registered multi-factor authenticator to complete session elevation.",
  },
  passkey: {
    badge: "WebAuthn Challenge",
    code: "MFA // FIDO2",
    title: "Passkey Verification",
    description:
      "Confirm identity via device biometrics, screen lock, or hardware security key.",
  },
  totp: {
    badge: "Time-Based Token",
    code: "MFA // TOTP",
    title: "Authenticator Code",
    description:
      "Enter the current six-digit challenge generated by your authenticator application.",
  },
  recovery_code: {
    badge: "Emergency Override",
    code: "MFA // VAULT",
    title: "Recovery Key",
    description:
      "Provide an unused single-use recovery code issued during enrollment.",
  },
};

export function AdminLoginPage() {
  const router = useRouter();

  const {
    challenge,
    availableMfaMethods,
    isPending,
    submitCredentials,
    verifyPasskey,
    verifyTotp,
    verifyRecoveryCode,
    resetChallenge,
  } = useAdminLoginFlow();

  const [selectedMethod, setSelectedMethod] =
    useState<AdminMfaMethod | null>(null);

  const [errorMessage, setErrorMessage] = useState("");

  async function handleCredentialsSubmit(
    payload: AdminLoginRequest,
  ): Promise<void> {
    setErrorMessage("");
    setSelectedMethod(null);

    try {
      await submitCredentials(payload);
    } catch (error) {
      setErrorMessage(
        error instanceof Error ? error.message : "Unable to sign in.",
      );
    }
  }

  async function completeLogin(
    verification: Promise<MfaVerificationResponse>,
  ): Promise<void> {
    setErrorMessage("");

    try {
      const response = await verification;

      if (!response.authenticated) {
        throw new Error(response.message || "Authentication failed.");
      }

      resetChallenge();
      router.replace("/dashboard");
    } catch (error) {
      setErrorMessage(
        error instanceof Error
          ? error.message
          : "Verification failed. Please try again.",
      );
    }
  }

  async function handlePasskeySubmit(): Promise<void> {
    await completeLogin(verifyPasskey());
  }

  async function handleTotpSubmit(code: string): Promise<void> {
    await completeLogin(verifyTotp(code));
  }

  async function handleRecoveryCodeSubmit(
    recoveryCode: string,
  ): Promise<void> {
    await completeLogin(verifyRecoveryCode(recoveryCode));
  }

  function handleBackToMethods(): void {
    setErrorMessage("");
    setSelectedMethod(null);
  }

  function handleRestartLogin(): void {
    resetChallenge();
    setSelectedMethod(null);
    setErrorMessage("");
  }

  function handleMethodSelect(method: AdminMfaMethod): void {

    setErrorMessage("");
    setSelectedMethod(method);
  }

  const currentStepKey = !challenge
    ? "credentials"
    : !selectedMethod
      ? "method"
      : selectedMethod;

  const meta = STEP_META[currentStepKey];

  return (
    <div className="relative flex min-h-screen flex-col justify-between bg-[var(--background)] text-[var(--foreground)] selection:bg-[var(--primary)] selection:text-[var(--background)]">
      <div
        aria-hidden="true"
        className="pointer-events-none fixed inset-0 bg-[radial-gradient(circle_at_top,rgba(165,139,101,0.12),transparent_58%)]"
      />

      <header className="relative z-10 border-b border-[var(--border)] bg-[var(--surface)]/90 backdrop-blur-sm">
        <div className="mx-auto flex h-16 max-w-6xl items-center justify-between px-6">
          <Link
            href="/"
            className="flex items-center gap-3 transition-opacity hover:opacity-80"
          >
            <span className="inline-flex size-8 items-center justify-center border border-[var(--accent)] bg-[var(--surface-muted)] font-mono text-xs font-semibold tracking-[0.18em] text-[var(--accent)]">
              BG
            </span>
            <div className="flex flex-col">
              <span className="text-sm font-semibold tracking-[0.22em] text-[var(--foreground)] uppercase">
                BAGGUAGE
              </span>
              <span className="font-mono text-[10px] tracking-[0.16em] text-[var(--muted-foreground)] uppercase">
                Admin Console
              </span>
            </div>
          </Link>

          <div className="flex items-center gap-4">
            <span className="hidden font-mono text-[11px] tracking-[0.14em] text-[var(--muted-foreground)] uppercase sm:inline">
              Restricted Environment
            </span>
            <Link
              href="/"
              className="border border-[var(--border)] bg-[var(--surface-muted)] px-3.5 py-1.5 text-[11px] font-semibold tracking-[0.18em] text-[var(--foreground)] uppercase transition-colors hover:border-[var(--accent)] hover:bg-[var(--surface)]"
            >
              Storefront
            </Link>
          </div>
        </div>
      </header>

      <main className="relative z-10 flex flex-1 items-center justify-center px-6 py-14">
        <Card className="w-full max-w-md rounded-none border border-[var(--border)] bg-[var(--card)] text-[var(--card-foreground)] shadow-[0_24px_60px_-28px_rgba(23,23,23,0.28)]">
          <div className="h-[3px] w-full bg-[var(--accent)]" />

          <CardContent className="space-y-8 p-8 sm:p-10">
            <div className="space-y-3 border-b border-[var(--border)] pb-6">
              <div className="flex items-center justify-between text-[10px] font-semibold tracking-[0.26em] text-[var(--accent)] uppercase">
                <span>{meta.badge}</span>
                <span className="font-mono text-[var(--muted-foreground)]">
                  {meta.code}
                </span>
              </div>

              <h1 className="text-3xl font-semibold tracking-[-0.03em] text-[var(--foreground)]">
                {meta.title}
              </h1>

              <p className="text-sm leading-relaxed text-[var(--muted-foreground)]">
                {meta.description}
              </p>
            </div>

            {!challenge ? (
              <AdminLoginForm
                onSubmit={handleCredentialsSubmit}
                isPending={isPending}
                errorMessage={errorMessage}
              />
            ) : !selectedMethod ? (
              <div className="space-y-5">
                <AdminMfaMethodSelector
                  methods={availableMfaMethods}
                  onSelect={handleMethodSelect}
                  isPending={isPending}
                />

                <Button
                  type="button"
                  variant="outline"
                  onClick={handleRestartLogin}
                  disabled={isPending}
                  className="h-11 w-full rounded-none border border-[var(--border)] bg-[var(--surface)] text-xs font-semibold tracking-[0.18em] text-[var(--foreground)] uppercase transition-colors hover:border-[var(--accent)] hover:bg-[var(--surface-muted)] hover:text-[var(--foreground)] disabled:opacity-50"
                >
                  Back to Sign In
                </Button>
              </div>
            ) : (
              <div className="space-y-5">
                {selectedMethod === "passkey" && (
                  <PasskeyLoginForm
                    onSubmit={handlePasskeySubmit}
                    onBack={handleBackToMethods}
                    isPending={isPending}
                    errorMessage={errorMessage}
                  />
                )}

                {selectedMethod === "totp" && (
                  <TotpLoginForm
                    onSubmit={handleTotpSubmit}
                    onBack={handleBackToMethods}
                    isPending={isPending}
                    errorMessage={errorMessage}
                  />
                )}

                {selectedMethod === "recovery_code" && (
                  <RecoveryCodeLoginForm
                    onSubmit={handleRecoveryCodeSubmit}
                    onBack={handleBackToMethods}
                    isPending={isPending}
                    errorMessage={errorMessage}
                  />
                )}
              </div>
            )}
          </CardContent>
        </Card>
      </main>

      <footer className="relative z-10 border-t border-[var(--border)] bg-[var(--surface)]/70">
        <div className="mx-auto flex max-w-6xl flex-col items-center justify-between gap-2 px-6 py-4 text-[11px] text-[var(--muted-foreground)] sm:flex-row">
          <span className="font-mono tracking-[0.12em] uppercase">
            BAGGUAGE · Operations &amp; Security
          </span>
          <span className="font-mono tracking-[0.12em]">
            All sessions are monitored &amp; audited
          </span>
        </div>
      </footer>
    </div>
  );
}