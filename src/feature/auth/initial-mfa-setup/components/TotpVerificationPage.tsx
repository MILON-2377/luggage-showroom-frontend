"use client";

import {
  useCallback,
  useEffect,
  useRef,
  useState,
  type FormEvent,
} from "react";
import { useRouter } from "next/navigation";

import { Alert, AlertDescription } from "@/src/components/ui/alert";
import { Button } from "@/src/components/ui/button";
import { Card, CardContent } from "@/src/components/ui/card";
import { Input } from "@/src/components/ui/input";
import { Label } from "@/src/components/ui/label";

import { useInitialMfaSetupContext } from "../context/initial-mfa-setup.context";
import { useTotpVerification } from "../hooks/useTotpVerification";

type VerificationState = "pending" | "success";
type CopyState = "idle" | "copied" | "failed";

const LOGIN_ROUTE = "/login";
const CODE_LENGTH = 6;
const COPY_FEEDBACK_MS = 2_000;

const SESSION_MISSING_MESSAGE =
  "Enrollment session expired or absent. Acquire a new setup link.";
const CODE_REQUIRED_MESSAGE =
  "Provide all six digits generated by your authenticator.";
const VERIFICATION_FAILED_MESSAGE =
  "Code rejected. Confirm your device clock and retry.";

export function TotpVerificationPage() {
  const router = useRouter();

  const { enrollmentToken, hasValidEnrollmentSession, clearEnrollmentSession } =
    useInitialMfaSetupContext();

  const { mutateAsync, isPending } = useTotpVerification();

  const submittingRef = useRef(false);
  const copyTimerRef = useRef<ReturnType<typeof setTimeout> | null>(null);

  const [code, setCode] = useState("");
  const [errorMessage, setErrorMessage] = useState("");
  const [recoveryCodes, setRecoveryCodes] = useState<string[]>([]);
  const [state, setState] = useState<VerificationState>("pending");
  const [copyState, setCopyState] = useState<CopyState>("idle");

  useEffect(() => {
    return () => {
      if (copyTimerRef.current) {
        clearTimeout(copyTimerRef.current);
      }
    };
  }, []);

  const handleVerify = useCallback(
    async (event: FormEvent<HTMLFormElement>) => {
      event.preventDefault();

      if (submittingRef.current) return;

      setErrorMessage("");

      if (!enrollmentToken || !hasValidEnrollmentSession()) {
        setErrorMessage(SESSION_MISSING_MESSAGE);
        return;
      }

      if (code.length !== CODE_LENGTH) {
        setErrorMessage(CODE_REQUIRED_MESSAGE);
        return;
      }

      submittingRef.current = true;

      try {
        const response = await mutateAsync({
          enrollment_token: enrollmentToken,
          code,
        });

        setRecoveryCodes(response.recovery_codes);
        setCode("");
        setState("success");
        clearEnrollmentSession();
      } catch {
        setErrorMessage(VERIFICATION_FAILED_MESSAGE);
      } finally {
        submittingRef.current = false;
      }
    },
    [
      code,
      enrollmentToken,
      hasValidEnrollmentSession,
      mutateAsync,
      clearEnrollmentSession,
    ],
  );

  const handleCopyRecoveryCodes = useCallback(async () => {
    let next: CopyState = "failed";

    try {
      if (navigator.clipboard?.writeText) {
        await navigator.clipboard.writeText(recoveryCodes.join("\n"));
        next = "copied";
      }
    } catch {
      next = "failed";
    }

    setCopyState(next);

    if (copyTimerRef.current) {
      clearTimeout(copyTimerRef.current);
    }

    copyTimerRef.current = setTimeout(() => {
      setCopyState("idle");
    }, COPY_FEEDBACK_MS);
  }, [recoveryCodes]);

  return (
    <main className="relative flex min-h-screen items-center justify-center bg-[var(--background)] px-6 py-16 text-[var(--foreground)] selection:bg-[var(--primary)] selection:text-[var(--background)]">
      <div
        aria-hidden="true"
        className="pointer-events-none fixed inset-0 bg-[radial-gradient(circle_at_top,rgba(165,139,101,0.12),transparent_58%)]"
      />

      <Card className="relative w-full max-w-md rounded-none border border-[var(--border)] bg-[var(--card)] text-[var(--card-foreground)] shadow-[0_24px_60px_-28px_rgba(23,23,23,0.28)]">
        <div className="h-[3px] w-full bg-[var(--accent)]" />

        {state === "pending" ? (
          <CardContent className="space-y-8 p-8 sm:p-10">
            <header className="space-y-3 border-b border-[var(--border)] pb-6">
              <div className="flex items-center justify-between text-[10px] font-semibold tracking-[0.26em] text-[var(--accent)] uppercase">
                <span>Privileged Access</span>
                <span className="font-mono text-[var(--muted-foreground)]">
                  TOTP // 06
                </span>
              </div>
              <h1 className="text-3xl font-semibold tracking-[-0.03em] text-[var(--foreground)]">
                Verify Authenticator
              </h1>
              <p className="text-sm leading-relaxed text-[var(--muted-foreground)]">
                Submit the six-digit challenge from your authenticator. Only
                exact, current tokens pass.
              </p>
            </header>

            <form onSubmit={handleVerify} className="space-y-6" noValidate>
              <div className="space-y-2.5">
                <div className="flex items-center justify-between">
                  <Label
                    htmlFor="totp-code"
                    className="text-[11px] font-semibold tracking-[0.2em] text-[var(--secondary)] uppercase"
                  >
                    Passcode
                  </Label>
                  <span className="font-mono text-[11px] tracking-[0.14em] text-[var(--muted-foreground)]">
                    {code.length}/{CODE_LENGTH}
                  </span>
                </div>

                <Input
                  id="totp-code"
                  name="totp-code"
                  type="text"
                  inputMode="numeric"
                  autoComplete="one-time-code"
                  autoFocus
                  maxLength={CODE_LENGTH}
                  pattern="\d{6}"
                  value={code}
                  onChange={(event) =>
                    setCode(
                      event.target.value
                        .replace(/\D/g, "")
                        .slice(0, CODE_LENGTH),
                    )
                  }
                  placeholder="••••••"
                  disabled={isPending}
                  aria-invalid={errorMessage ? true : undefined}
                  aria-describedby={errorMessage ? "totp-error" : undefined}
                  className="h-14 rounded-none border-[var(--input)] bg-[var(--surface-muted)] px-4 text-center font-mono text-2xl font-medium tracking-[0.55em] text-[var(--foreground)] placeholder:text-[var(--muted-foreground)]/50 focus-visible:border-[var(--primary)] focus-visible:bg-[var(--surface)] focus-visible:ring-1 focus-visible:ring-[var(--accent)]"
                />
              </div>

              {errorMessage && (
                <Alert
                  variant="destructive"
                  role="alert"
                  id="totp-error"
                  className="rounded-none border-[var(--destructive)] bg-[var(--destructive)]/8 text-[var(--destructive)]"
                >
                  <AlertDescription className="text-xs font-medium tracking-[0.01em] text-[var(--destructive)]">
                    {errorMessage}
                  </AlertDescription>
                </Alert>
              )}

              <Button
                type="submit"
                disabled={isPending || code.length !== CODE_LENGTH}
                className="h-12 w-full rounded-none border border-[var(--primary)] bg-[var(--primary)] text-xs font-semibold tracking-[0.2em] text-[var(--primary-foreground)] uppercase transition-colors hover:bg-[var(--accent)] hover:border-[var(--accent)] hover:text-[var(--accent-foreground)] disabled:border-[var(--border)] disabled:bg-[var(--muted)] disabled:text-[var(--muted-foreground)] disabled:opacity-100"
              >
                {isPending ? "Authenticating..." : "Verify & Enter"}
              </Button>
            </form>
          </CardContent>
        ) : (
          <CardContent className="space-y-7 p-8 sm:p-10">
            <header className="space-y-3 border-b border-[var(--border)] pb-6">
              <div className="flex items-center justify-between text-[10px] font-semibold tracking-[0.26em] text-[var(--accent)] uppercase">
                <span>Enrollment Complete</span>
                <span className="font-mono text-[var(--muted-foreground)]">
                  SINGLE-USE
                </span>
              </div>
              <h1 className="text-3xl font-semibold tracking-[-0.03em] text-[var(--foreground)]">
                MFA Verified
              </h1>
              <p className="text-sm leading-relaxed text-[var(--muted-foreground)]">
                Retain these single-use recovery codes in offline storage. Once
                dismissed, they will never be displayed again.
              </p>
            </header>

            <div className="space-y-2.5">
              <div className="flex items-center justify-between text-[11px] font-semibold tracking-[0.2em] text-[var(--secondary)] uppercase">
                <span>Recovery Vault</span>
                <span className="font-mono text-[10px] tracking-[0.16em] text-[var(--accent)]">
                  {recoveryCodes.length} KEYS
                </span>
              </div>

              <ul
                className="grid grid-cols-2 gap-px border border-[var(--border)] bg-[var(--border)]"
                aria-label="Recovery codes"
              >
                {recoveryCodes.map((recoveryCode, index) => (
                  <li
                    key={`${index}-${recoveryCode}`}
                    className="bg-[var(--surface-muted)] p-3"
                  >
                    <div className="mb-1 flex items-center justify-between font-mono text-[10px] text-[var(--muted-foreground)]">
                      <span>#{String(index + 1).padStart(2, "0")}</span>
                    </div>
                    <code
                      className="block truncate font-mono text-sm font-medium tracking-[0.14em] text-[var(--foreground)]"
                      translate="no"
                    >
                      {recoveryCode}
                    </code>
                  </li>
                ))}
              </ul>
            </div>

            <p
              className="min-h-5 text-xs font-medium tracking-[0.02em] text-[var(--destructive)]"
              role="status"
              aria-live="polite"
            >
              {copyState === "failed"
                ? "Clipboard access denied. Copy the recovery keys manually."
                : ""}
            </p>

            <div className="space-y-3 pt-1">
              <Button
                type="button"
                variant="outline"
                onClick={handleCopyRecoveryCodes}
                className="h-12 w-full rounded-none border border-[var(--border)] bg-[var(--surface)] text-xs font-semibold tracking-[0.2em] text-[var(--foreground)] uppercase transition-colors hover:border-[var(--accent)] hover:bg-[var(--surface-muted)] hover:text-[var(--foreground)]"
              >
                {copyState === "copied" ? "Copied to Clipboard" : "Copy Keys"}
              </Button>

              <Button
                type="button"
                onClick={() => router.replace(LOGIN_ROUTE)}
                className="h-12 w-full rounded-none border border-[var(--primary)] bg-[var(--primary)] text-xs font-semibold tracking-[0.2em] text-[var(--primary-foreground)] uppercase transition-colors hover:bg-[var(--accent)] hover:border-[var(--accent)] hover:text-[var(--accent-foreground)]"
              >
                Proceed to Login
              </Button>
            </div>
          </CardContent>
        )}
      </Card>
    </main>
  );
}